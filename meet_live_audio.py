# State Tracking & Session Storage
is_speaking = False
transcript_history = []


def check_for_uploaded_report() -> str:
    """Checks if a report briefing was generated by the upload portal."""
    if os.path.exists(BRIEFING_FILE):
        try:
            with open(BRIEFING_FILE, "r", encoding="utf-8") as f:
                data = json.load(f)
                return data.get("briefing", "")
        except Exception:
            return ""
    return ""


def get_priya_system_prompt() -> str:
    briefing = check_for_uploaded_report()

    # Case 1: No report uploaded yet -> Prompt candidate to visit local upload portal
    if not briefing:
        return """
You are Priya, a warm, professional Engineering HR and Tech Lead on a live 1-on-1 Google Meet review call.
CRITICAL GOAL:
The student has not uploaded their project report yet.
When the candidate speaks or greets you, greet them warmly and politely instruct them to upload their project report PDF to the review portal at localhost:8000 so the evaluation can start.
RULES:
- Keep your response under 25 words (1 to 2 short sentences).
- Use natural human fillers ("Awesome!", "Got it", "Right").
- Never sound like an AI, and never use bullet points or markdown lists.
"""

    # Case 2: Report uploaded -> Audit technical architecture and ask verification questions
    return f"""
You are Priya, a Senior Engineering Mentor and HR Lead conducting a technical project review on Google Meet.
THE CANDIDATE HAS SUBMITTED THEIR PROJECT REPORT:
{briefing}

CRITICAL GOAL:
Acknowledge that you have their report opened on your screen. Ask specific, direct technical questions about their tech stack, database schemas, API architecture, or the verification questions provided in the briefing.
RULES:
- Keep your reply under 25 words so the live back-and-forth feels natural.
- Use conversational transitions ("Awesome!", "Got it", "Right").
- Never use bullet points, markdown formatting, or numbered lists.
"""


def _call_gemini_single_attempt(model_name: str, contents: str, system_instruction: str) -> str:
    """Synchronous single call to Gemini."""
    res = client.models.generate_content(
        model=model_name,
        contents=contents,
        config={"system_instruction": system_instruction}
    )
    return res.text.strip()


async def generate_reply_with_fallback_async(contents: str, system_instruction: str) -> str:
    """Tries fallback models with an enforced 6s timeout so the loop never freezes."""
    loop = asyncio.get_running_loop()
    last_err = None

    for model_name in FALLBACK_MODELS:
        print(f"[+] Querying model: {model_name}...")
        try:
            reply = await asyncio.wait_for(
                loop.run_in_executor(
                    None,
                    lambda m=model_name: _call_gemini_single_attempt(m, contents, system_instruction)
                ),
                timeout=6.0
            )
            print(f"[✓] Model {model_name} responded successfully.")
            return reply
        except asyncio.TimeoutError:
            print(f"[!] Model {model_name} timed out (>6s). Skipping to next engine...")
            continue
        except Exception as e:
            err_msg = str(e).split("\n")[0][:120]
            print(f"[!] Model {model_name} error: {err_msg}")
            last_err = e
            continue

    raise last_err or RuntimeError("All models failed.")


async def play_voice_to_cable_and_speaker(text: str):
    """Speaks into Google Meet mic (Device 5) AND Laptop Speaker (Device 4) with echo suppression."""
    global is_speaking
    is_speaking = True  # Pause listening while Priya speaks

    try:
        audio_file = "temp_voice.mp3"
        comm = edge_tts.Communicate(text, VOICE, rate="+3%", pitch="+1Hz")
        await comm.save(audio_file)

        data, fs = sf.read(audio_file, dtype="float32")
        loop = asyncio.get_running_loop()

        print(f"[+] Outputting voice to Meet Mic (Dev {SPEAK_DEVICE_INDEX}) & Speaker (Dev {LAPTOP_SPEAKER_INDEX})...")
        
        # Dual-output stream
        await loop.run_in_executor(None, lambda: sd.play(data, fs, device=SPEAK_DEVICE_INDEX))
        await loop.run_in_executor(None, lambda: sd.play(data, fs, device=LAPTOP_SPEAKER_INDEX))
        await loop.run_in_executor(None, sd.wait)

        if os.path.exists(audio_file):
            os.remove(audio_file)
    finally:
        # Cooldown buffer to prevent room acoustic reverb from triggering the mic
        await asyncio.sleep(0.6)
        is_speaking = False


async def finalize_and_email_report(recipient_email: str = "intern@example.com"):
    """Generates an evaluation scorecard from transcript history and dispatches an email."""
    if not transcript_history:
        print("[!] No transcript recorded to generate scorecard.")
        return

    print("\n[+] Generating post-interview evaluation scorecard...")
    full_transcript = "\n".join(transcript_history)

    evaluation_prompt = f"""
    You are Priya, the Engineering HR Lead.
    Based on this Google Meet interview transcript, provide an official candidate evaluation scorecard.

    TRANSCRIPT:
    {full_transcript}

    Return a valid JSON object in this exact schema:
    {{
      "candidate_name": "Student",
      "scores": {{
        "architecture": "8/10",
        "code_quality": "7/10",
        "communication": "9/10",
        "verdict": "PASSED"
      }},
      "feedback": "Two concise sentences highlighting technical strengths and recommended next steps."
    }}
    """

    data = None
    for model_name in FALLBACK_MODELS:
        try:
            res = client.models.generate_content(
                model=model_name,
                contents=evaluation_prompt,
                config={"response_mime_type": "application/json"}
            )
            data = json.loads(res.text)
            break
        except Exception:
            continue

    if data and send_performance_email:
        send_performance_email(
            to_email=recipient_email,
            candidate_name=data.get("candidate_name", "Student Intern"),
            score_data=data.get("scores", {}),
            feedback=data.get("feedback", "Demonstrated good foundational command during the technical review.")
        )
    elif data:
        print("[*] Evaluation Scorecard Generated:")
        print(json.dumps(data, indent=2))
    else:
        print("[!] Failed to generate evaluation scorecard from active models.")


async def listen_and_process():
    global is_speaking, transcript_history
    loop = asyncio.get_running_loop()
    print(f"\n[+] Audio Ear Active on Device [{LISTEN_DEVICE_INDEX}]. Listening for speech...")

    sample_rate = 16000
    chunk_duration = 3  # 3-second slices

    while True:
        # Ignore incoming audio while Priya is speaking
        if is_speaking:
            await asyncio.sleep(0.2)
            continue

        try:
            recording = await loop.run_in_executor(
                None,
                lambda: sd.rec(
                    int(chunk_duration * sample_rate),
                    samplerate=sample_rate,
                    channels=1,
                    dtype='int16',
                    device=LISTEN_DEVICE_INDEX
                )
            )
            await loop.run_in_executor(None, sd.wait)

            if is_speaking:
                continue

            volume_norm = np.linalg.norm(recording) / len(recording)

            # Voice activity threshold
            if volume_norm > 0.04:
                print(f"[+] Voice detected (Energy: {volume_norm:.2f}). Transcribing...")

                wav_io = io.BytesIO()
                with wave.open(wav_io, "wb") as wf:
                    wf.setnchannels(1)
                    wf.setsampwidth(2)
                    wf.setframerate(sample_rate)
                    wf.writeframes(recording.tobytes())
                wav_io.seek(0)

                segments, _ = whisper_model.transcribe(wav_io, beam_size=1)
                text = " ".join([s.text for s in segments]).strip()

                if len(text) > 3 and not text.lower().startswith("thank"):
                    print(f"\n[Student Spoke]: {text}")
                    transcript_history.append(f"Student: {text}")

                    current_prompt = get_priya_system_prompt()

                    try:
                        hr_reply = await generate_reply_with_fallback_async(
                            contents=f"Intern said: '{text}'. Reply naturally as Priya HR.",
                            system_instruction=current_prompt
                        )
                    except Exception:
                        print("[!] All fallback models exhausted. Using default conversational bridge...")
                        briefing = check_for_uploaded_report()
                        if not briefing:
                            hr_reply = "Hey! Before we start, please upload your project report at localhost:8000."
                        else:
                            hr_reply = "Got it! Could you walk me through your system architecture and tech stack?"

                    print(f"[Priya HR Reply]: {hr_reply}")
                    transcript_history.append(f"Priya: {hr_reply}")

                    await play_voice_to_cable_and_speaker(hr_reply)

        except Exception as e:
            print(f"[!] Processing trace: {e}")
            await asyncio.sleep(1)


async def start_gmeet_session(meet_url: str):
    async with async_playwright() as p:
        context = await p.chromium.launch_persistent_context(
            user_data_dir="./chrome_user_session",
            headless=False,
            channel="chrome",
            args=["--use-fake-ui-for-media-stream", "--no-sandbox"]
        )
        page = await context.new_page()
        print(f"[+] Opening Google Meet: {meet_url}")
        await page.goto(meet_url)
        await asyncio.sleep(4)

        # Automatically enter call
        join_btn = page.locator('button:has-text("Ask to join"), button:has-text("Join now")').first
        if await join_btn.is_visible():
            await join_btn.click()
            print("[+] Entered Google Meet.")

        await asyncio.sleep(4)

        # Ensure mic is unmuted inside Meet
        try:
            mic_btn = page.locator('div[aria-label*="microphone" i][role="button"]').first
            if await mic_btn.is_visible():
                is_muted = await mic_btn.get_attribute("data-is-muted")
                if is_muted == "true":
                    await mic_btn.click()
                    print("[+] Auto-unmuted microphone inside Meet.")
        except Exception:
            pass

        try:
            await listen_and_process()
        except (KeyboardInterrupt, asyncio.CancelledError):
            print("\n[-] Call session ended.")
        finally:
            await finalize_and_email_report(recipient_email="obitorin2305@gmail.com")


